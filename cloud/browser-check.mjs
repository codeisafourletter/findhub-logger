import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { historyServer } from './serve-history.mjs';
const server=historyServer(); await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const browser=await chromium.launch({executablePath:process.env.CHROME_BIN || '/usr/bin/google-chrome',headless:true,args:['--no-sandbox']});
try {
  const context=await browser.newContext({acceptDownloads:true}); const page=await context.newPage(); const errors=[]; const remote=[];
  page.on('pageerror',error=>errors.push(error.message));
  page.on('request',request=>{if(!request.url().startsWith('http://127.0.0.1:'))remote.push(request.url());});
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.getByRole('button',{name:'Explore demo'}).click();
  assert.match(await page.locator('#notice').textContent(),/DEMO.*Synthetic/);
  assert.equal(await page.locator('.entity').count(),2);
  await page.getByRole('button',{name:/River phone/}).click();
  assert.match(await page.locator('#detail').textContent(),/85 min|1.4 hours/);
  assert.equal(await page.locator('svg circle').count(),4);
  await page.locator('#filter').selectOption('stale'); assert.equal(await page.locator('.entity').count(),1);
  assert.match(await page.locator('#detail').textContent(),/First export fresh Sheet data/);
  await page.locator('#filter').selectOption('all'); await page.locator('#search').fill('missing'); assert.equal(await page.locator('.entity').count(),0); await page.locator('#search').fill('');
  const privateFixture=[{captured_at:'2026-11-04T12:00:00Z',person:'Fixture phone',latitude:10,longitude:20,address:'<img src=x onerror=alert(1)>',battery:'75%',displayed_age:'5 minutes ago'}];
  await page.locator('#import').setInputFiles({name:'history.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(privateFixture))});
  await page.waitForFunction(()=>document.getElementById('notice').textContent.includes('PRIVATE IMPORT'));
  assert.equal(await page.locator('.entity').count(),1); assert.equal(await page.locator('#detail img').count(),0);
  assert.match(await page.locator('#detail').textContent(),/<img src=x/);
  await page.locator('#import').setInputFiles({name:'broken.json',mimeType:'application/json',buffer:Buffer.from('[{"latitude":999}]')});
  await page.waitForFunction(()=>document.getElementById('notice').textContent.includes('Import not applied'));
  assert.equal(await page.locator('.entity').count(),1);
  const downloadPromise=page.waitForEvent('download'); await page.getByRole('button',{name:'Export all JSON'}).click(); const download=await downloadPromise;
  const stream=await download.createReadStream(); let body=''; for await(const chunk of stream)body+=chunk;
  const exported=JSON.parse(body); assert.equal(exported.records[0].person,'Fixture phone'); assert.equal(exported.records[0].longitude,20);
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.deepEqual(await page.evaluate(()=>({local:localStorage.length,session:sessionStorage.length})),{local:0,session:0});
  await page.evaluate(() => {
    const original = File.prototype.text;
    File.prototype.text = function() { if(this.name==='delayed.json') return new Promise(resolve => { window.finishDelayedImport = () => resolve('[{"captured_at":"2026-11-04T12:00:00Z","person":"Delayed fixture","latitude":10,"longitude":20}]'); }); return original.call(this); };
  });
  await page.locator('#import').setInputFiles({name:'delayed.json',mimeType:'application/json',buffer:Buffer.from('[]')});
  await page.waitForFunction(()=>typeof window.finishDelayedImport==='function');
  await page.getByRole('button',{name:'Clear session'}).click();
  await page.evaluate(async()=>{window.finishDelayedImport(); await new Promise(resolve=>setTimeout(resolve,0));});
  assert.equal(await page.locator('#empty').isVisible(),true);
  assert.match(await page.locator('#notice').textContent(),/Session cleared/);
  await page.locator('#import').setInputFiles({name:'sheet.csv',mimeType:'text/csv',buffer:Buffer.from('captured_at,person,latitude,longitude\n2026-11-04T12:00:00Z,CSV phone,10,20')});
  await page.waitForFunction(()=>document.getElementById('notice').textContent.includes('PRIVATE IMPORT'));
  assert.match(await page.locator('.entity').textContent(),/CSV phone/);
  await page.reload(); assert.equal(await page.locator('#empty').isVisible(),true);
  assert.deepEqual(errors,[]); assert.deepEqual(remote,[]);
  console.log('Browser journey passed: demo, filters, JSON/CSV import, failed-import retention, XSS text safety, export, mobile, clear/reload, no remote requests.');
} finally { await browser.close(); await new Promise(resolve=>server.close(resolve)); }
